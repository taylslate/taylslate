import { describe, expect, it } from "vitest";
import { generateIOPdf } from "./io-pdf";
import type { InsertionOrder, IOLineItem } from "@/lib/data/types";

function line(overrides: Partial<IOLineItem> = {}): IOLineItem {
  return {
    id: "line-1",
    format: "podcast",
    post_date: "2026-05-01",
    guaranteed_downloads: 12_000,
    show_name: "The Daily Briefing",
    placement: "mid-roll",
    is_scripted: false,
    is_personal_experience: true,
    reader_type: "host_read",
    content_type: "evergreen",
    pixel_required: false,
    gross_rate: 342,
    gross_cpm: 28.5,
    price_type: "cpm",
    net_due: 342,
    verified: false,
    make_good_triggered: false,
    ...overrides,
  };
}

function order(overrides: Partial<InsertionOrder> = {}, items?: IOLineItem[]): InsertionOrder {
  const lineItems = items ?? [line()];
  return {
    id: "io-1",
    io_number: "IO-2026-0004",
    deal_id: "deal-1",
    advertiser_name: "Aurora Sleep",
    advertiser_contact_name: "Brand Lead",
    advertiser_contact_email: "brand@aurora.example",
    publisher_name: "The Daily Briefing",
    publisher_contact_name: "Host",
    publisher_contact_email: "host@daily.fm",
    total_downloads: lineItems.reduce((sum, item) => sum + item.guaranteed_downloads, 0),
    total_gross: lineItems.reduce((sum, item) => sum + item.gross_rate, 0),
    total_net: lineItems.reduce((sum, item) => sum + item.net_due, 0),
    payment_terms: "Net 30 EOM",
    competitor_exclusion: [],
    exclusivity_days: 90,
    rofr_days: 30,
    cancellation_notice_days: 14,
    download_tracking_days: 45,
    make_good_threshold: 0.1,
    status: "draft",
    created_at: "2026-04-23T00:00:00Z",
    updated_at: "2026-04-23T00:00:00Z",
    ...overrides,
    line_items: items ?? overrides.line_items ?? lineItems,
  };
}

function textOf(io: InsertionOrder): string {
  return generateIOPdf(io).toString("latin1");
}

describe("negotiated IO terms on the editor PDF", () => {
  it("renders an unedited IO with the stored payment sentence and calendar-day cancellation", () => {
    const text = textOf(order());
    expect(text).toContain("Net 30 EOM");
    expect(text).toContain("Generated by Taylslate");
    expect(text).toContain("30-day right of first refusal");
    expect(text).toContain("45-day tracking window");
    expect(text).toContain("make-good episode");
    expect(text).toContain("14 calendar days written notice");
    expect(text).not.toContain("business days");
    expect(text).not.toContain("AGENCY OF RECORD");
    expect(text).toContain("Mid-Roll");
    expect(text).toContain("28.50");
    expect(text).toContain("12,000");
    expect(text).toContain("PUBLISHER / TALENT REPRESENTATIVE");
    expect(text).toContain("ADVERTISER");
  });

  it("prints the free-text payment term and drops Taylslate wording when off-platform", () => {
    const text = textOf(
      order({ payment_off_platform: true, payment_terms: "Net 30 via ACH" })
    );
    expect(text).toContain("Net 30 via ACH");
    expect(text).not.toContain("platform fee");
    expect(text).not.toContain("Pay-as-delivers");
    expect(text).not.toContain("Taylslate");
  });

  it("prices a flat line per spot and leaves CPM and downloads blank", () => {
    const text = textOf(
      order({}, [
        line({
          price_type: "flat_rate",
          gross_rate: 2500,
          net_due: 2500,
          gross_cpm: 40,
          guaranteed_downloads: 50_000,
        }),
      ])
    );
    expect(text).toContain("Flat, $2,500.00 per spot");
    expect(text).toContain("2,500.00");
    expect(text).not.toContain("50,000");
    expect(text).not.toContain("40.00");
  });

  it("uses each line's placement and format", () => {
    const text = textOf(
      order({}, [
        line({ placement: "pre-roll", spot_format: "Host-read" }),
        line({
          id: "line-2",
          placement: "post-roll",
          spot_format: "Produced",
          post_date: "2026-05-08",
        }),
      ])
    );
    expect(text).toContain("Pre-Roll");
    expect(text).toContain("Post-Roll");
    expect(text).toContain("Host-read");
    expect(text).toContain("Produced");
    expect(text).not.toContain("Mid-Roll");
  });

  it("names the agency of record and still signs as advertiser and publisher", () => {
    const text = textOf(
      order({
        agency_name: "Left Field",
        agency_contact_name: "Alex Rivera",
        agency_contact_email: "alex@leftfield.example",
        payer: "agency",
      })
    );
    expect(text).toContain("AGENCY OF RECORD");
    expect(text).toContain("Left Field");
    expect(text).toContain("Alex Rivera, alex@leftfield.example");
    expect(text).toContain("Agency of record");
    expect(text).toContain("PUBLISHER / TALENT REPRESENTATIVE");
    expect(text).toContain("ADVERTISER");
  });

  it("leaves a switched-off term out and keeps the others", () => {
    const rofrOff = textOf(order({ rofr_enabled: false }));
    expect(rofrOff).not.toContain("right of first refusal");
    expect(rofrOff).toContain("tracking window");
    expect(rofrOff).toContain("make-good episode");

    const trackingOff = textOf(order({ download_tracking_enabled: false }));
    expect(trackingOff).not.toContain("tracking window");
    expect(trackingOff).toContain("right of first refusal");
    expect(trackingOff).toContain("make-good episode");

    const makeGoodOff = textOf(order({ make_good_enabled: false }));
    expect(makeGoodOff).not.toContain("make-good episode");
    expect(makeGoodOff).toContain("tracking window");
    expect(makeGoodOff).toContain("right of first refusal");
  });
});
